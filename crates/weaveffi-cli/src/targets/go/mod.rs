/// Per-target configuration for [`GoGenerator`].
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct GoConfig {
    /// Go module path written to `go.mod`. Defaults to the package name.
    pub name: Option<String>,
    /// Go package name. Defaults to the C prefix without underscores.
    pub package: Option<String>,
}

/// The marker Go tools recognize on generated files (linters skip them and
/// editors warn before an edit).
const GENERATED: &str = "// Code generated by WeaveFFI. DO NOT EDIT.\n\n";

/// Every identity-derived name the generated module uses.
pub(crate) struct Names {
    /// The Go module path (`go.mod`): the configured `name`, else the
    /// package name.
    pub(crate) module_path: String,
    /// The Go package name: the configured `package`, else the C prefix
    /// without underscores, escaped if it's a Go keyword.
    pub(crate) package: String,
    /// The native library base name the bindings link (`-l{library}`).
    pub(crate) library: String,
    /// The bundled C header's file name, `{library}.h`.
    pub(crate) header: String,
}

impl Names {
    pub(crate) fn new(model: &Model, config: &GoConfig) -> Self {
        let id = &model.identity;
        let configured = |v: &Option<String>| {
            v.as_deref()
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .map(str::to_string)
        };
        Self {
            module_path: configured(&config.name).unwrap_or_else(|| id.name.clone()),
            package: configured(&config.package)
                .map(|p| crate::lang::escape_ident(&p, crate::lang::GO_KEYWORDS))
                .unwrap_or_else(|| names::package(&id.prefix)),
            library: id.library.clone(),
            header: crate::targets::c::header_name(model),
        }
    }
}

/// What every renderer needs beyond the declaration it renders.
#[derive(Clone, Copy)]
pub(crate) struct Ctx<'a> {
    /// The model being rendered.
    pub(crate) model: &'a Model,
    /// The C symbol prefix.
    pub(crate) prefix: &'a str,
    /// The Go package name.
    pub(crate) package: &'a str,
    /// The Go name of every declaration.
    pub(crate) names: &'a GoNames,
    /// Doc text in Go spelling.
    pub(crate) docs: &'a DocNames<'a>,
    /// The types that cross inside value buffers.
    pub(crate) codecs: &'a BufferTypes,
}

impl Ctx<'_> {
    /// The Go function (of type `func(wvFailure) error`) mapping a failure
    /// of a callable with error strategy `e` onto its error: the domain's
    /// mapper, or the generic `*Error`.
    pub(crate) fn mapper(&self, e: &ErrorStrategy) -> String {
        match e {
            ErrorStrategy::Domain(d) => self.names.domain(d).mapper.clone(),
            ErrorStrategy::Trap | ErrorStrategy::Untyped => "wvFailure.err".into(),
        }
    }

    /// The Go expression mapping the `wvFailure` value `failure` onto the
    /// error of a callable with error strategy `e` (see [`Self::mapper`]).
    pub(crate) fn map_failure(&self, e: &ErrorStrategy, failure: &str) -> String {
        match e {
            ErrorStrategy::Domain(d) => format!("{}({failure})", self.names.domain(d).mapper),
            ErrorStrategy::Trap | ErrorStrategy::Untyped => format!("{failure}.err()"),
        }
    }
}

/// Go backend: emits a cgo module binding the C ABI exposed by the
/// underlying cdylib.
pub struct GoGenerator {
    config: GoConfig,
}

impl From<GoConfig> for GoGenerator {
    fn from(config: GoConfig) -> Self {
        Self { config }
    }
}

impl Target for GoGenerator {
    fn name(&self) -> &'static str {
        "go"
    }

    fn linkage(&self) -> Linkage {
        Linkage::Link
    }

    fn fixed_files(&self) -> &'static [&'static str] {
        &["README.md", "codec.go", "go.mod", "runtime.go"]
    }

    fn render(&self, model: &Model) -> Vec<OutputFile> {
        let dir = Utf8PathBuf::new();
        render_files(model, &self.config)
            .into_iter()
            .map(|(name, contents)| OutputFile::new(dir.join(name), contents))
            .collect()
    }

    /// The module directory at `go/{package}/` with each desktop library
    /// under `lib/<platform>/` and a cgo preamble that links the right one.
    fn package(&self, model: &Model, ctx: &PackageContext<'_>) -> Result<Vec<Artifact>> {
        Ok(package_files(model, ctx, &self.config))
    }
}

/// Every file of the generated module, as `(file name, contents)` pairs.
pub(crate) fn render_files(model: &Model, config: &GoConfig) -> Vec<(String, String)> {
    let names = Names::new(model, config);
    let runtime_names = RuntimeNames {
        package: &names.package,
        prefix: model.prefix(),
        header: &names.header,
    };
    vec![
        ("go.mod".to_string(), render_go_mod(&names.module_path)),
        ("README.md".to_string(), render_readme(&names)),
        (
            names.header.clone(),
            render_c_header_from_model(model, &names.header),
        ),
        ("bindings.go".to_string(), render_bindings(model, &names)),
        ("runtime.go".to_string(), render_runtime(&runtime_names)),
        ("codec.go".to_string(), render_codec(&runtime_names)),
    ]
}

/// The head every Go file starts with: the WeaveFFI prelude and the Go
/// generated-code marker.
pub(crate) fn go_prelude() -> String {
    format!("{}{GENERATED}", render_prelude(CommentStyle::DoubleSlash))
}

/// Render `bindings.go`: the cgo preamble, the imports, the load-time
/// checks, every declaration, and the composite codecs.
pub(crate) fn render_bindings(model: &Model, names: &Names) -> String {
    let go_names = GoNames::new(model);
    let doc_names = DocNames::new(model, &go_names);
    let codecs = BufferTypes::of(model);
    let ctx = Ctx {
        model,
        prefix: model.prefix(),
        package: &names.package,
        names: &go_names,
        docs: &doc_names,
        codecs: &codecs,
    };

    let mut w = CodeWriter::tabs();
    w.raw(go_prelude());
    w.line(format!(
        "// Package {} binds the {} native library.",
        names.package, names.library
    ));
    w.line("//");
    w.line("// Call [Check] at startup to find out whether the linked library is the");
    w.line("// one these bindings were generated for.");
    w.line(format!("package {}", names.package));
    w.blank();
    render_preamble(&mut w, model, names, &codecs);
    render_imports(&mut w, model);
    render_checks(&mut w, model);
    render_declarations(&mut w, &ctx);
    codecs.render_composites(&mut w);

    // Exactly one blank line before the trailer keeps the file gofmt-clean.
    let mut out = w.finish();
    out.truncate(out.trim_end().len());
    out.push_str("\n\n");
    out.push_str(&render_trailer(CommentStyle::DoubleSlash, "bindings.go"));
    out
}

/// Write the cgo preamble: the link flag, the header, and the declarations
/// of the exported trampolines and static vtables.
fn render_preamble(w: &mut CodeWriter, model: &Model, names: &Names, codecs: &BufferTypes) {
    w.line("/*");
    w.line(format!("#cgo LDFLAGS: -l{}", names.library));
    if model.callables().any(|f| f.deprecated.is_some()) {
        // The bindings call deprecated functions on the user's behalf; only
        // the user's own calls should warn, through Go's `Deprecated:` docs.
        w.line("#cgo CFLAGS: -Wno-deprecated-declarations");
    }
    w.line(format!("#include \"{}\"", names.header));
    if codecs.has_interfaces() {
        // Widening an object token to a pointer in C keeps `go vet` from
        // flagging a "possible misuse of unsafe.Pointer". Each preamble
        // helper is compiled into every cgo translation unit, some of which
        // never call it.
        w.line(
            "__attribute__((unused)) static void* wvHandlePtr(uintptr_t h) { return (void*)h; }",
        );
    }
    emit_preamble_decls(w, model);
    w.line("*/");
    w.line("import \"C\"");
    w.blank();
}

/// Write the standard-library imports `bindings.go` uses; everything else
/// lives in `runtime.go` and `codec.go`, whose imports are fixed.
fn render_imports(w: &mut CodeWriter, model: &Model) {
    let has_async = model.has_async();
    let packages = [
        (has_async, "context"),
        (model.has_iterators(), "iter"),
        (
            !model.interfaces.is_empty() || !model.callbacks.is_empty() || has_async,
            "unsafe",
        ),
    ];
    let used: Vec<&str> = packages
        .iter()
        .filter(|(on, _)| *on)
        .map(|(_, p)| *p)
        .collect();
    if used.is_empty() {
        return;
    }
    w.block("import (", ")", |w| {
        for p in used {
            w.line(format!("\"{p}\""));
        }
    });
    w.blank();
}

/// Write `wvCheckLibrary`, the load-time checks the Go `Check` runs: the
/// ABI revision, then every declaration's contract function against the
/// hash these bindings were generated with. The bindings link the library,
/// so a declaration it lacks fails to link instead.
fn render_checks(w: &mut CodeWriter, model: &Model) {
    w.line("// wvCheckLibrary checks the linked library's ABI revision and the contract");
    w.line("// of every declaration these bindings were generated with.");
    w.block("func wvCheckLibrary() error {", "}", |w| {
        w.block("if err := wvCheckABI(); err != nil {", "}", |w| {
            w.line("return err");
        });
        w.block("return wvCheckContract([]wvContractRow{", "})", |w| {
            for row in contract::rows(model) {
                w.line(format!(
                    "{{uint64(C.{}()), {}, {}}},",
                    row.symbol,
                    contract::hex(row.hash),
                    go_str(&row.path)
                ));
            }
        });
    });
    w.blank();
}

/// Render every declaration: error domains, enums, records, callback
/// interfaces, interfaces, and free functions.
fn render_declarations(w: &mut CodeWriter, ctx: &Ctx) {
    let model = ctx.model;
    for e in &model.errors {
        render_error(w, ctx, e);
    }
    for e in &model.enums {
        if e.is_rich() {
            render_rich_enum(w, ctx, e);
        } else {
            render_enum(w, ctx, e);
        }
    }
    for r in &model.records {
        render_record(w, ctx, r);
    }
    for cb in &model.callbacks {
        render_callback_interface(w, ctx, cb);
    }
    for i in &model.interfaces {
        render_interface(w, ctx, i);
    }
    for f in &model.functions {
        render_function(w, ctx, f, ctx.names.function(f), None);
    }
}
